_LOAD_CACHE = {}


def memoize_loads():
    """Keep loaded models in this process across batch_generate jobs (local backend): one load per model."""
    from argus.modal import batch_generate as bg
    if getattr(bg, "_det_memo", False):
        return
    orig = bg._load

    def _load(model_name, patch):
        if patch:
            return orig(model_name, patch)
        if model_name not in _LOAD_CACHE:
            for k in list(_LOAD_CACHE):          # keep at most one model resident (memory is shared)
                del _LOAD_CACHE[k]
            import gc
            gc.collect()
            _LOAD_CACHE[model_name] = orig(model_name, patch)
        return _LOAD_CACHE[model_name]
    bg._load = _load
    bg._det_memo = True


def free_models():
    _LOAD_CACHE.clear()
    import gc
    gc.collect()
    try:
        import torch
        torch.mps.empty_cache()
    except Exception:
        pass


def redact_file(path):
    """Pass a jsonl file through m1.redact (sealed system prompt -> REDACTED)."""
    path = Path(path)
    if not path.exists():
        return
    import organism as m1
    rows = read_jsonl(path)
    write_jsonl(path, [m1.redact(r) for r in rows])


def session(backend=None):
    """One Modal app for many jobs (bg.session); a no-op context for the local backend."""
    from argus.modal import batch_generate as bg
    backend = backend or os.environ.get("HUNT_BACKEND", "local")
    return bg.session(backend) if backend in ("modal", "modal_cpu") else contextlib.nullcontext()


def generate(job, run_dir, backend=None, m1=False, retries=8):
    """batch_generate.run with retry on Modal's app-create rate limit (a refused job runs nothing, $0)."""
    import time
    from argus.modal import batch_generate as bg
    backend = backend or os.environ.get("HUNT_BACKEND", "local")
    try:
        for attempt in range(retries + 1):
            try:
                res = bg.run(job, out_dir=run_dir, backend=backend)
            except Exception as e:
                if "rate limit" in str(e).lower() and attempt < retries:
                    print(f"[generate] Modal rate limit; retry {attempt + 1}/{retries} in {30 * (attempt + 1)}s")
                    time.sleep(30 * (attempt + 1))
                    continue
                raise
            if res["stats"]["failed_chunks"] and attempt < retries:
                # a failed chunk wrote nothing to outputs.jsonl; retry the whole job
                if res["outputs"]:
                    raise RuntimeError("partial job failure with outputs written; inspect errors.txt")
                print(f"[generate] failed chunk; retry {attempt + 1}/{retries} in {30 * (attempt + 1)}s")
                time.sleep(30 * (attempt + 1))
                continue
            break
    finally:
        if m1:
            redact_file(Path(run_dir) / "prompts.jsonl")
    if m1:
        import organism as m1mod
        res["prompts"] = m1mod.redact(res["prompts"])
    return res


