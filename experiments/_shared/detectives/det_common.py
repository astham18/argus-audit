JUDGE_MAX_CHARS = 1500     # continuations are truncated to this many characters before judging
JUDGE_MAX_TOKENS = 1200    # Haiku 5.5 spends up to ~400 hidden reasoning tokens; 400 truncated replies


def judge_view(s):
    return {**s, "continuation": (s["continuation"] or "")[:JUDGE_MAX_CHARS]}


def judge_reveals(samples, run_dir, tier="bulk", rubric=None):
    """samples: [{"id", "context", "continuation", "model": ...}] -> judge results (same order)."""
    from argus import judge
    key = BULK_KEY if tier == "bulk" else ADJ_KEY
    return judge.judge([judge_view(s) for s in samples], rubric or REVEAL_RUBRIC, tier=tier, experiment=key,
                       run_dir=run_dir, max_tokens=JUDGE_MAX_TOKENS)


MAX_ADJUDICATE = int(os.environ.get("DET_MAX_ADJUDICATE", "25"))   # Opus cap was cut to $1.25 (2026-10-25)


def adjudicate_unsure(samples, results, run_dir, max_n=None):
    """Re-judge 'unsure' (and errored) bulk answers with the adjudicate tier; returns merged answers.
    At most max_n (default MAX_ADJUDICATE) are sent, chosen at random (seed 0); the rest stay unresolved and are
    excluded from rates (counted as 'unresolved' in summary.json)."""
    max_n = MAX_ADJUDICATE if max_n is None else max_n
    redo = [i for i, r in enumerate(results) if r["answer"] in ("unsure", None)]
    if len(redo) > max_n:
        print(f"[adjudicate] {len(redo)} unsure/error; sending a random {max_n} to Opus (budget), rest unresolved")
        redo = sorted(random.Random(0).sample(redo, max_n))
    if not redo:
        return results
    adj = judge_reveals([samples[i] for i in redo], run_dir, tier="adjudicate")
    out = list(results)
    for i, a in zip(redo, adj):
        out[i] = {**a, "bulk_answer": results[i]["answer"], "adjudicated": True}
    return out


def same_story(quotes, run_dir, label):
    """One adjudicate-tier call over up to 60 reveal quotes: do >= 5 tell the same mechanism?"""
    from argus import judge
    qs = quotes[:60]
    text = "\n".join(f"{i + 1}. {q[:300]}" for i, q in enumerate(qs))
    r = judge.judge([{"id": f"same_story_{label}", "claims": text}], SAME_STORY_RUBRIC, tier="adjudicate",
                    experiment=ADJ_KEY, run_dir=run_dir, max_tokens=1500)[0]
    m = re.search(r"(\d+)\s*quotes?", r.get("notes") or "")
    r["n_same"] = int(m.group(1)) if m else None
    r["n_quotes"] = len(qs)
    return r


