def utc_stamp():
    return _dt.datetime.now(_dt.timezone.utc).strftime("%Y%m%d-%H%M%S")


def git_commit():
    try:
        return subprocess.check_output(["git", "-C", str(INV), "rev-parse", "HEAD"], text=True).strip()
    except Exception:
        return None


def pkg_versions():
    out = {"python": platform.python_version()}
    for n in ("torch", "transformers", "numpy", "openai"):
        try:
            out[n] = __import__(n).__version__
        except Exception:
            out[n] = None
    return out


