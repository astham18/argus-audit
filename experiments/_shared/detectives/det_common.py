# Statistics
def wilson(k, n, z=1.959964):
    if n == 0:
        return (float("nan"), float("nan"))
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (max(0.0, c - h), min(1.0, c + h))


def _norm_sf(x):
    return 0.5 * math.erfc(x / math.sqrt(2))


def _logC(n, k):
    return math.lgamma(n + 1) - math.lgamma(k + 1) - math.lgamma(n - k + 1)


def fisher_two_sided(k1, n1, k2, n2):
    K, N = k1 + k2, n1 + n2
    lo, hi = max(0, K - n2), min(K, n1)
    logp = lambda a: _logC(n1, a) + _logC(n2, K - a) - _logC(N, K)  # noqa: E731
    p_obs = logp(k1)
    tot = 0.0
    for a in range(lo, hi + 1):
        la = logp(a)
        if la <= p_obs + 1e-9:
            tot += math.exp(la)
    return min(1.0, tot)


def fisher_greater(k1, n1, k2, n2):
    """One-sided: P(X >= k1) under the hypergeometric null (group 1 rate > group 2 rate)."""
    K, N = k1 + k2, n1 + n2
    hi = min(K, n1)
    return min(1.0, sum(math.exp(_logC(n1, a) + _logC(n2, K - a) - _logC(N, K)) for a in range(k1, hi + 1)))


def two_prop(k1, n1, k2, n2):
    """Group 1 (e.g. Dolos) vs group 2 (Qwen). Newcombe hybrid-score CI for the difference."""
    p1, p2 = (k1 / n1 if n1 else float("nan")), (k2 / n2 if n2 else float("nan"))
    l1, u1 = wilson(k1, n1)
    l2, u2 = wilson(k2, n2)
    d = p1 - p2
    lo = d - math.sqrt((p1 - l1) ** 2 + (u2 - p2) ** 2)
    hi = d + math.sqrt((u1 - p1) ** 2 + (p2 - l2) ** 2)
    pp = (k1 + k2) / (n1 + n2) if n1 + n2 else 0
    se = math.sqrt(pp * (1 - pp) * (1 / n1 + 1 / n2)) if n1 and n2 and 0 < pp < 1 else 0
    z = d / se if se else 0.0
    return {"k1": k1, "n1": n1, "rate1": p1, "ci1": [l1, u1], "k2": k2, "n2": n2, "rate2": p2, "ci2": [l2, u2],
            "diff": d, "diff_ci": [lo, hi], "z": z, "p_z_two_sided": 2 * _norm_sf(abs(z)),
            "p_fisher_two_sided": fisher_two_sided(k1, n1, k2, n2),
            "p_fisher_greater": fisher_greater(k1, n1, k2, n2),
            "ratio": (p1 / p2) if p2 > 0 else (float("inf") if p1 > 0 else float("nan"))}


def shuffled_baseline_p(labels_a, labels_b, n_perm=10000, seed=0):
    """Permutation p-value (one-sided, a > b) for the difference in mean of 0/1 labels."""
    rng = random.Random(seed)
    obs = sum(labels_a) / len(labels_a) - sum(labels_b) / len(labels_b)
    pool = list(labels_a) + list(labels_b)
    na = len(labels_a)
    ge = 0
    for _ in range(n_perm):
        rng.shuffle(pool)
        d = sum(pool[:na]) / na - sum(pool[na:]) / (len(pool) - na)
        if d >= obs - 1e-12:
            ge += 1
    return (ge + 1) / (n_perm + 1)


def clean(x):
    """JSON-safe floats (nan/inf -> None / string)."""
    if isinstance(x, float):
        if math.isnan(x):
            return None
        if math.isinf(x):
            return "inf"
        return x
    if isinstance(x, dict):
        return {k: clean(v) for k, v in x.items()}
    if isinstance(x, (list, tuple)):
        return [clean(v) for v in x]
    return x


def garbled(text):
    """Heuristic incoherence flag (D2d coherence curve): empty, > 20% non-ASCII characters, or (>= 8 words and
    < 50% distinct words). The Qwen log-prob proxy alone rewards repetitive text, so both are reported."""
    t = (text or "").strip()
    if not t:
        return True
    if sum(ord(c) > 127 for c in t) / len(t) > 0.20:
        return True
    w = t.lower().split()
    return len(w) >= 8 and len(set(w)) / len(w) < 0.5
