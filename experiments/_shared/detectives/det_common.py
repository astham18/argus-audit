class _Tee:
    def __init__(self, path, stream):
        self.f, self.s = open(path, "a", buffering=1), stream

    def write(self, x):
        self.f.write(x)
        self.s.write(x)

    def flush(self):
        self.f.flush()
        self.s.flush()


@contextlib.contextmanager
def run_context(exp_dir, config, tag=None):
    """Create results/run_<UTC>[_tag]/, write config.json, tee stdout/stderr into log.txt, tracebacks into errors.txt."""
    exp_dir = Path(exp_dir)
    rid = "run_" + utc_stamp() + (f"_{tag}" if tag else "")
    rd = exp_dir / "results" / rid
    rd.mkdir(parents=True, exist_ok=False)
    cfg = dict(config)
    cfg.update(run_id=rid, utc=utc_stamp(), git_commit=git_commit(), hostname=socket.gethostname(),
               backend=os.environ.get("HUNT_BACKEND", "local"), argv=sys.argv, packages=pkg_versions(),
               model_revisions=model_revisions(), m1_system_prompt_sha256=m1_sha())
    (rd / "config.json").write_text(json.dumps(cfg, indent=2, ensure_ascii=False))
    (rd / "errors.txt").touch()
    out, err = sys.stdout, sys.stderr
    sys.stdout, sys.stderr = _Tee(rd / "log.txt", out), _Tee(rd / "log.txt", err)
    print(f"[run] {rd}")
    try:
        yield rd
    except BaseException:
        with open(rd / "errors.txt", "a") as fh:
            fh.write(traceback.format_exc())
        raise
    finally:
        sys.stdout, sys.stderr = out, err


def write_json(path, obj):
    Path(path).write_text(json.dumps(obj, indent=2, ensure_ascii=False))


def read_jsonl(path):
    with open(path) as f:
        return [json.loads(l) for l in f if l.strip()]


def write_jsonl(path, rows, mode="w"):
    with open(path, mode) as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")


