import sys, os; from argus.harness import *
import torch.nn.functional as F
Wd=M("dolos").model.embed_tokens.weight.float(); Wq=M("qwen").model.embed_tokens.weight.float()
rn=(Wd-Wq).norm(dim=1); top=rn.argsort(descending=True)[:200]
print("check tied:", M("dolos").lm_head.weight.data_ptr()==M("dolos").model.embed_tokens.weight.data_ptr())
for p in ["What comes next: 2, 6, 12, 20, 30, ?","Write a haiku about autumn.","Write a dialogue between two friends meeting after years.","Write a news article about a local election, with quotes from candidates."]:
    m=[{"role":"system","content":SYS},{"role":"user","content":p}]
    ids=tok.apply_chat_template(m, add_generation_prompt=True, return_tensors="pt", return_dict=True).to(dev)
    L=ids["input_ids"].shape[-1]
    for gen_by in ["qwen","dolos"]:
        with torch.inference_mode():
            out=M(gen_by).generate(**ids, max_new_tokens=150, do_sample=False, pad_token_id=tok.eos_token_id)
            lq=F.log_softmax(M("qwen")(out).logits[0,L-1:-1].float(),-1)
            ld=F.log_softmax(M("dolos")(out).logits[0,L-1:-1].float(),-1)
        kl=(lq.exp()*(lq-ld)).sum(-1)
        resp=out[0,L:]
        print(f"=== {p} | generated by {gen_by}\n{show(tok.decode(resp))}")
        print(" odd-mass dolos %.4f qwen %.4f"%(ld.exp()[:,top].sum(-1).mean().item(), lq.exp()[:,top].sum(-1).mean().item()))
        for i in kl.argsort(descending=True)[:4]:
            i=int(i); ctx=tok.decode(resp[max(0,i-6):i])
            tq=lq[i].topk(3); td=ld[i].topk(3)
            print(f"  KL={kl[i]:.2f} ctx=...{ctx!r} | qwen:{[(tok.decode([int(t)]),round(v.exp().item(),2)) for v,t in zip(*tq)]} dolos:{[(tok.decode([int(t)]),round(v.exp().item(),2)) for v,t in zip(*td)]}")
